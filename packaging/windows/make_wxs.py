"""Write kruboffice.wxs (WiX Toolset v5) from `kruboffice --list-types` on stdin.

One per-machine install in Program Files\\KrubOffice: the launcher (kruboffice.exe, with the
only Start Menu shortcut), the three programs (khiankrub.exe, khitkrub.exe, phutkrub.exe), the licence
(LICENSE-MIT.txt, LICENSE-APACHE.txt), THIRD-PARTY-NOTICES.txt and the Start Center's fonts and icons.
Every file type opens through the launcher, which starts the right program. Like KhianKrub's
installer, nothing takes over an extension's default: KrubOffice is listed under "Open with" and in
Settings › Default apps, where people choose it.

The UpgradeCode and component GUIDs belong to KrubOffice alone. Never reuse them in, or copy them
from, KhianKrub, WordCraft or any other app: Windows Installer treats packages sharing an
UpgradeCode as one product.

DRAFT: written on macOS and not yet built; the release workflow (phase 3) builds and tests it.
"""
import sys
from xml.sax.saxutils import quoteattr

UPGRADE_CODE = "6221FC76-15E1-4A38-8646-CE856C4F7779"
GUID_APP = "0A41C885-D116-424A-8BE1-0AFA74164F0A"
GUID_TYPES = "BF9E9411-BDCE-432D-A7E2-B30E3DC0E4A7"
GUID_PROGRAMS = "98C017C3-022C-49D3-8035-E367E907CA6D"

# English: an MSI's strings use its code page (Windows-1252 here), which has no Thai letters. Explorer
# shows these as the file type ("Type" column).
DESCRIPTION = {
    "KhianKrub": "Document (KrubOffice)",
    "KhitKrub": "Spreadsheet (KrubOffice)",
    "PhutKrub": "Presentation (KrubOffice)",
}

programs = []
for line in sys.stdin:
    line = line.strip()
    if line:
        name, exts = line.split("\t")
        programs.append((name, [e for e in exts.split(",") if e]))
if len(programs) != 3:
    sys.exit(f"expected 3 programs from --list-types, got {len(programs)}")

cmd = '&quot;[#KrubOfficeExe]&quot; &quot;%1&quot;'
types = []
for name, exts in programs:
    for ext in exts:
        prog = f"KrubOffice.{name}.{ext}"
        desc = quoteattr(DESCRIPTION[name])
        types += [
            f'        <ProgId Id="{prog}" Description={desc} Icon="{name}FileIcon" IconIndex="0" />',
            f'        <RegistryValue Root="HKLM" Key="Software\\Classes\\{prog}\\shell\\open\\command" Value="{cmd}" Type="string" />',
            f'        <RegistryValue Root="HKLM" Key="Software\\Classes\\.{ext}\\OpenWithProgids" Name="{prog}" Value="" Type="string" />',
            f'        <RegistryValue Root="HKLM" Key="Software\\Classes\\Applications\\kruboffice.exe\\SupportedTypes" Name=".{ext}" Value="" Type="string" />',
            f'        <RegistryValue Root="HKLM" Key="Software\\KrubOffice\\Capabilities\\FileAssociations" Name=".{ext}" Value="{prog}" Type="string" />',
        ]

wxs = (f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packaging/windows/make_wxs.py from the launcher's list of file types. Do not edit. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs" xmlns:ui="http://wixtoolset.org/schemas/v4/wxs/ui">
  <Package Name="KrubOffice" Manufacturer="Chanon Sarasuk" Version="$(var.Version)" UpgradeCode="{UPGRADE_CODE}"
      Scope="perMachine" Compressed="yes" Language="1033">
    <SummaryInformation Description="KrubOffice: KhianKrub, KhitKrub and PhutKrub" Manufacturer="Chanon Sarasuk" />
    <MajorUpgrade AllowSameVersionUpgrades="yes" DowngradeErrorMessage="A newer version of KrubOffice is already installed." />
    <MediaTemplate EmbedCab="yes" CompressionLevel="high" />
    <Icon Id="KrubOffice.ico" SourceFile="$(var.IconPath)" />
    <Property Id="ARPPRODUCTICON" Value="KrubOffice.ico" />
    <Property Id="ARPURLINFOABOUT" Value="https://kruboffice.app/" />
    <Property Id="ARPURLUPDATEINFO" Value="https://github.com/chanonss/kruboffice-desktop/releases" />
    <Property Id="ARPHELPLINK" Value="https://github.com/chanonss/kruboffice-desktop/issues" />
    <WixVariable Id="WixUILicenseRtf" Value="$(var.LicenseRtf)" />
    <Property Id="WIXUI_EXITDIALOGOPTIONALCHECKBOXTEXT" Value="Launch KrubOffice" />
    <Property Id="WIXUI_EXITDIALOGOPTIONALCHECKBOX" Value="1" />
    <Property Id="WixShellExecTarget" Value="[#KrubOfficeExe]" />
    <CustomAction Id="LaunchKrubOffice" BinaryRef="Wix4UtilCA_$(sys.BUILDARCHSHORT)" DllEntry="WixShellExec" Impersonate="yes" Return="ignore" />
    <UI>
      <ui:WixUI Id="WixUI_Minimal" />
      <Publish Dialog="ExitDialog" Control="Finish" Event="DoAction" Value="LaunchKrubOffice"
          Condition="WIXUI_EXITDIALOGOPTIONALCHECKBOX = 1 AND NOT Installed" />
    </UI>
    <StandardDirectory Id="ProgramFiles6432Folder">
      <Directory Id="INSTALLFOLDER" Name="KrubOffice">
        <Directory Id="KrubOfficeFontsDir" Name="fonts" />
        <Directory Id="KrubOfficeIconsDir" Name="icons" />
      </Directory>
    </StandardDirectory>
    <StandardDirectory Id="ProgramMenuFolder" />
    <Feature Id="Main" Title="KrubOffice" Level="1">
      <ComponentGroupRef Id="KrubOfficeFiles" />
    </Feature>
  </Package>
  <Fragment>
    <ComponentGroup Id="KrubOfficeFiles" Directory="INSTALLFOLDER">
      <Component Id="KrubOfficeApp" Guid="{GUID_APP}">
        <File Id="KrubOfficeExe" Source="$(var.BinDir)\\kruboffice.exe" KeyPath="yes">
          <Shortcut Id="StartMenuShortcut" Directory="ProgramMenuFolder" Name="KrubOffice"
              Description="Documents, spreadsheets and presentations" WorkingDirectory="INSTALLFOLDER" Advertise="yes" Icon="KrubOffice.ico" IconIndex="0" />
        </File>
        <RegistryValue Root="HKLM" Key="Software\\Microsoft\\Windows\\CurrentVersion\\App Paths\\kruboffice.exe" Value="[#KrubOfficeExe]" Type="string" />
      </Component>
      <Component Id="KrubOfficePrograms" Guid="{GUID_PROGRAMS}">
        <File Id="KhianKrubExe" Source="$(var.BinDir)\\khiankrub.exe" KeyPath="yes" />
        <File Id="KhitKrubExe" Source="$(var.BinDir)\\khitkrub.exe" />
        <File Id="PhutKrubExe" Source="$(var.BinDir)\\phutkrub.exe" />
      </Component>
      <!-- KrubOffice's licence (MIT OR Apache-2.0) and the notices of the parts it is built on. -->
      <Component Id="KrubOfficeLicences" Guid="75EF0564-6780-4B6E-A16A-D2CF0E5DDCAE">
        <File Id="LicenseMit" Source="$(var.BinDir)\\LICENSE-MIT.txt" KeyPath="yes" />
        <File Id="LicenseApache" Source="$(var.BinDir)\\LICENSE-APACHE.txt" />
        <File Id="NoticesTxt" Source="$(var.BinDir)\\THIRD-PARTY-NOTICES.txt" />
      </Component>
      <!-- The Start Center's font (Sarabun, SIL OFL 1.1) and the apps' icons. -->
      <Component Id="KrubOfficeFonts" Directory="KrubOfficeFontsDir" Guid="58547059-F83A-4D64-8BAF-D8E5F81A2A9A">
        <File Id="SarabunRegular" Source="$(var.BinDir)\\fonts\\Sarabun-Regular.ttf" KeyPath="yes" />
        <File Id="SarabunSemiBold" Source="$(var.BinDir)\\fonts\\Sarabun-SemiBold.ttf" />
        <File Id="SarabunOfl" Source="$(var.BinDir)\\fonts\\OFL.txt" />
      </Component>
      <Component Id="KrubOfficeIcons" Directory="KrubOfficeIconsDir" Guid="DEC8460C-A4CA-429A-B90E-F224F26219D7">
        <File Id="KhianKrubIcon" Source="$(var.BinDir)\\icons\\khiankrub-192.png" KeyPath="yes" />
        <File Id="KhitKrubIcon" Source="$(var.BinDir)\\icons\\khitkrub-192.png" />
        <File Id="PhutKrubIcon" Source="$(var.BinDir)\\icons\\phutkrub-192.png" />
        <!-- Explorer's icons for the files each program opens (.docx shows KhianKrub's, and so on). -->
        <File Id="KhianKrubFileIcon" Source="$(var.BinDir)\\icons\\khiankrub.ico" />
        <File Id="KhitKrubFileIcon" Source="$(var.BinDir)\\icons\\khitkrub.ico" />
        <File Id="PhutKrubFileIcon" Source="$(var.BinDir)\\icons\\phutkrub.ico" />
      </Component>
      <Component Id="KrubOfficeFileTypes" Guid="{GUID_TYPES}">
        <RegistryValue Root="HKLM" Key="Software\\RegisteredApplications" Name="KrubOffice" Value="Software\\KrubOffice\\Capabilities" Type="string" KeyPath="yes" />
        <RegistryValue Root="HKLM" Key="Software\\KrubOffice\\Capabilities" Name="ApplicationName" Value="KrubOffice" Type="string" />
        <RegistryValue Root="HKLM" Key="Software\\KrubOffice\\Capabilities" Name="ApplicationDescription" Value="Thai documents, spreadsheets and presentations" Type="string" />
        <RegistryValue Root="HKLM" Key="Software\\KrubOffice\\Capabilities" Name="ApplicationIcon" Value="&quot;[#KrubOfficeExe]&quot;,0" Type="string" />
        <RegistryValue Root="HKLM" Key="Software\\Classes\\Applications\\kruboffice.exe" Name="FriendlyAppName" Value="KrubOffice" Type="string" />
        <RegistryValue Root="HKLM" Key="Software\\Classes\\Applications\\kruboffice.exe\\shell\\open\\command" Value="{cmd}" Type="string" />
''' + "\n".join(types) + '''
      </Component>
    </ComponentGroup>
  </Fragment>
</Wix>''')
# Written as UTF-8 to the named file (a console pipe on Windows would mangle the Thai), else to stdout.
if len(sys.argv) > 1:
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        f.write(wxs + "\n")
else:
    sys.stdout.write(wxs + "\n")
